#!/usr/bin/env python3
"""Write docs/hadith-review.md: every hadith in the notes that is still marked unverified.

Run: python3 scripts/hadith_checklist.py

A reviewer ticks an entry after checking its Arabic text, source and grade against a hadith
source, then sets "verified": true (and fixes the fields) in that episode's notes.json.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SERIES = ROOT / "public" / "series"
OUT = ROOT / "docs" / "hadith-review.md"


def stamp(seconds):
    s = int(seconds)
    h, m = divmod(s // 60, 60)
    return f"{h}:{m:02d}:{s % 60:02d}" if h else f"{m}:{s % 60:02d}"


def unverified():
    """Yield (series title, notes, hadith) for each unverified hadith, in series and episode order."""
    for index_file in sorted(SERIES.glob("*/index.json")):
        meta = json.loads(index_file.read_text())
        order = {e["id"]: i for i, e in enumerate(meta.get("episodes", []))}
        found = []
        for notes_file in index_file.parent.glob("*/notes.json"):
            notes = json.loads(notes_file.read_text())
            found.append(notes)
        for notes in sorted(found, key=lambda n: order.get(n["id"], 999)):
            for d in notes.get("dalil", []):
                if d.get("kind") == "hadith" and not d.get("verified"):
                    yield meta.get("title", index_file.parent.name), notes, d


def render():
    rows = list(unverified())
    lines = [
        "# Hadith review checklist",
        "",
        "Generated by `python3 scripts/hadith_checklist.py`. Do not edit by hand.",
        "",
        f"{len(rows)} hadith entries are still marked \"Teks perlu disemak\". For each one, check the Arabic text,",
        "the source and the grade against a hadith source, then fix the entry in the episode's `notes.json` and set",
        "`\"verified\": true`. Re-run the script and it drops off this list.",
    ]
    current = None
    for series, notes, d in rows:
        if notes["id"] != current:
            current = notes["id"]
            heading = f"Ep {notes['episode']}: {notes['title']}" if notes.get("episode") else notes["title"]
            lines += ["", f"## {heading}", ""]
        link = f"https://www.youtube.com/watch?v={notes['youtubeId']}&t={int(d['t'])}s"
        lines += [
            f"- [ ] **{d['ref']}** · [{stamp(d['t'])}]({link}) · `{notes['id']}/{d['id']}`",
            f"  - Arabic: {d.get('arabic') or '(none)'}",
            f"  - Terjemahan: {d.get('translation', '')}",
            f"  - Perawi: {d.get('narrator', '')} · Sumber: {d.get('source', '')} · Darjat: {d.get('grade') or 'belum dinilai'}",
        ]
    return "\n".join(lines) + "\n", len(rows)


if __name__ == "__main__":
    text, count = render()
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text)
    print(f"{count} unverified hadith -> {OUT.relative_to(ROOT)}")
