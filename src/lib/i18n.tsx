const dict = { ms, en }
export type Key = keyof typeof ms
type Vars = Record<string, string | number>

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: Key, v?: Vars) => string }>({
  lang: 'ms',
  setLang: () => {},
  t: (k) => ms[k],
})

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem('nota-lang')
      if (saved === 'ms' || saved === 'en') return saved
    } catch {}
    return navigator.language.toLowerCase().startsWith('ms') ? 'ms' : 'en'
  })
  useEffect(() => {
    document.documentElement.lang = lang
    try {
      localStorage.setItem('nota-lang', lang)
    } catch {}
  }, [lang])
  const t = useCallback(
    (k: Key, v?: Vars) => dict[lang][k].replace(/\{(\w+)\}/g, (_, name) => String(v?.[name] ?? '')),
    [lang],
  )
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export const useT = () => useContext(Ctx)
